//! Stage discovery logic, shared by `build.rs` and `tests/stage_discovery.rs`.
//!
//! Kept std-only and free of `cargo:` output so the test can drive it against
//! throwaway directories.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// Names a stage module cannot take: Rust keywords (strict, reserved and
/// edition-2024 weak ones that break `mod x;`), plus the item the generated
/// file defines itself.
pub const RESERVED: &[&str] = &[
    "abstract",
    "as",
    "async",
    "await",
    "become",
    "box",
    "break",
    "const",
    "continue",
    "crate",
    "do",
    "dyn",
    "else",
    "enum",
    "extern",
    "false",
    "final",
    "fn",
    "for",
    "gen",
    "if",
    "impl",
    "in",
    "let",
    "loop",
    "macro",
    "match",
    "mod",
    "move",
    "mut",
    "override",
    "priv",
    "pub",
    "ref",
    "return",
    "self",
    "static",
    "struct",
    "super",
    "trait",
    "true",
    "try",
    "type",
    "typeof",
    "unsafe",
    "unsized",
    "use",
    "virtual",
    "where",
    "while",
    "yield",
    "register_all",
];

/// `(module name, source file)` for every stage module, sorted by name.
///
/// `Err` carries a message for the person who added the offending file.
pub fn discover(dir: &Path) -> Result<Vec<(String, PathBuf)>, String> {
    let entries = fs::read_dir(dir).map_err(|e| format!("reading {}: {e}", dir.display()))?;
    let mut modules = Vec::new();
    for entry in entries {
        let path = entry
            .map_err(|e| format!("reading {}: {e}", dir.display()))?
            .path();
        let file_name = path.file_name().unwrap().to_string_lossy().into_owned();
        let (name, source) = if path.is_dir() {
            let source = path.join("mod.rs");
            if !source.is_file() {
                continue; // not a module, e.g. a folder of shaders or assets
            }
            (file_name.clone(), source)
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            let stem = path.file_stem().unwrap().to_string_lossy().into_owned();
            if stem == "mod" {
                continue;
            }
            let folder = dir.join(&stem);
            if folder.join("mod.rs").is_file() {
                return Err(format!(
                    "src/stages/{file_name} and src/stages/{stem}/mod.rs both define stage '{stem}'; keep one"
                ));
            }
            if folder.is_dir() {
                // A `#[path]`-loaded file resolves `mod x;` beside itself
                // (src/stages/x.rs), so `{stem}/` can never hold its submodules.
                return Err(format!(
                    "src/stages/{file_name} sits next to a src/stages/{stem}/ folder, but a stage \
                     file cannot have submodules there; move it to src/stages/{stem}/mod.rs, or \
                     rename the folder"
                ));
            }
            (stem, path)
        } else {
            continue; // README, rustfmt `.rs.bk` backups, ...
        };
        if let Err(why) = check_name(&name) {
            return Err(format!(
                "src/stages/{file_name}: {why}; rename it to a snake_case Rust identifier"
            ));
        }
        modules.push((name, source));
    }
    modules.sort();
    Ok(modules)
}

pub fn check_name(name: &str) -> Result<(), String> {
    let mut chars = name.chars();
    let first_ok = chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_');
    if !first_ok || name == "_" || !chars.all(|c| c.is_ascii_alphanumeric() || c == '_') {
        return Err(format!("'{name}' is not a valid module name"));
    }
    if RESERVED.contains(&name) {
        return Err(format!("'{name}' is a reserved name"));
    }
    Ok(())
}

/// The generated `stages_gen.rs` source.
pub fn render(modules: &[(String, PathBuf)]) -> String {
    let mut s = String::from(
        "// @generated by build.rs from the contents of src/stages/. Do not edit.\n\n",
    );
    for (name, source) in modules {
        // `{:?}` emits a valid Rust string literal, escaping Windows backslashes.
        writeln!(
            s,
            "#[path = {:?}]\npub mod {name};",
            source.display().to_string()
        )
        .unwrap();
    }
    s.push_str("\n/// Register every stage module's node kinds. Generated by `build.rs`.\n");
    s.push_str("pub fn register_all(reg: &mut crate::exec::Registry) {\n");
    for (name, _) in modules {
        writeln!(s, "    {name}::register(reg);").unwrap();
    }
    s.push_str("}\n");
    s
}
